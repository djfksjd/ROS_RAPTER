#!/usr/bin/env python3
"""Build sim/raptor_r03.xml: R-02 (sim/raptor_r02.xml) plus an active hip yaw axis per leg (user decision 2026-10-31,
docs/STAGED_PLAN.ko.md). Nothing else changes in the MJCF; motors, transmissions and masses of model rev 3 are set by
RunEnv(model_rev=3) from sim/rl/rev3_b.json.

Joint order roll -> yaw -> pitch (Cassie): the yaw hinge is a second joint of {side}_hip_roll_link, declared after the
roll joint, so it turns with the roll and carries the thigh. Axis z of the hip-roll link frame, through the hip pitch
joint (the thigh frame coincides with the roll link frame in R-02), range +-0.5 rad (ASSUMED: about Cassie's +-0.4 rad
hip yaw, widened for turning; to be checked against leg-leg clearance in the turning stage). The actuator is added
after the hip roll actuator so that RunEnv's joint list reads roll, yaw, pitch, knee, ankle pitch, ankle roll per leg.

The ROS URDF/xacro (src/raptor_description) is NOT changed yet: MuJoCo-only until the ROS side is updated.
Usage: .venv-sim/bin/python sim/build_r03.py [--out sim/raptor_r03.xml]
"""
import argparse
from pathlib import Path

import mujoco

SIM = Path(__file__).resolve().parent
YAW_RANGE = .5
ATTR = ('ctrlrange', 'ctrllimited', 'forcelimited', 'forcerange', 'biastype', 'gainprm', 'biasprm', 'gaintype', 'dyntype')


def build(src=SIM/'raptor_r02.xml'):
    spec = mujoco.MjSpec.from_file(str(src))
    spec.modelname = 'raptor_r03'
    old = [(a.name, a.target, {k: getattr(a, k) for k in ATTR}) for a in spec.actuators]
    for a in list(spec.actuators):
        spec.delete(a)
    for side in ('left', 'right'):
        roll = spec.joint(f'{side}_hip_roll_joint')
        b = spec.body(f'{side}_hip_roll_link')
        j = b.add_joint(name=f'{side}_hip_yaw_joint', type=mujoco.mjtJoint.mjJNT_HINGE, axis=[0, 0, 1], pos=[0, 0, 0],
                        range=[-YAW_RANGE, YAW_RANGE], limited=mujoco.mjtLimited.mjLIMITED_TRUE)
        j.actfrcrange = roll.actfrcrange
        j.armature, j.damping, j.frictionloss = roll.armature, roll.damping, roll.frictionloss
    for name, target, attr in old:
        names = [name]
        if name.endswith('_hip_roll_joint'):
            names.append(name.replace('_hip_roll_joint', '_hip_yaw_joint'))
        for n in names:
            a = spec.add_actuator(name=n, target=n, trntype=mujoco.mjtTrn.mjTRN_JOINT)
            for k, v in attr.items():
                setattr(a, k, v)
    return spec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(SIM/'raptor_r03.xml'))
    a = ap.parse_args()
    spec = build()
    m = spec.compile()
    xml = spec.to_xml()
    Path(a.out).write_text('<!-- Generated by sim/build_r03.py from sim/raptor_r02.xml (adds hip yaw). Do not edit. -->\n' + xml)
    print(f'wrote {a.out}: nu={m.nu}, actuators', [m.actuator(i).name for i in range(m.nu)])


if __name__ == '__main__':
    main()
