"""Write sim/rl/realism_robstride_rev3.json from realism_robstride_v2.json (evidence 167) for model rev 3 (evidence 187):
motor assignment from sim/rl/rev3_b.json, RS04 thermal fit (thermal_fit_rs04.json), vendor T-N curve cap on, friction of
the new axes scaled through their external ratios like v2. Run from repo root."""
import copy, json, sys
import numpy as np
sys.path.insert(0, 'sim/rl'); sys.path.insert(0, 'modeling')
from knee_linkage_study import fourbar_N
from run_env import fourbar_band
E = 'docs/evidence/187-stage0-rev3-model'
v2 = json.load(open('sim/rl/realism_robstride_v2.json'))
ax = json.load(open('sim/rl/rev3_b.json'))
fit = json.load(open(f'{E}/eval/thermal_fit_rs04.json'))['fitted']
mods = json.load(open('docs/design/motor_candidates.json'))['modules']
out = copy.deepcopy(v2)
out['_comment'] = ('Model rev 3 (stage 0, option B, evidence 186-187): realism_robstride_v2.json with the motor assignment of '
                   'sim/rl/rev3_b.json (RS04 hip pitch 0.85 speed-up belt, RS04 knee four-bar, RS06 hip roll 2.5 belt, RS06 hip yaw '
                   '1.5 belt, tail RS03/RS06 direct), the RS04 thermal fit to its manual overload table, and the vendor 48 V T-N '
                   'curve cap (motor.tn_curve). Generated by docs/evidence/187-stage0-rev3-model/eval/make_realism_rev3.py; '
                   'tests/test_rev3_model.py checks it against rev3_b.json. Not validated against hardware.')
m = out['motor']
m['tn_curve'] = True
m['tn_curve_note'] = 'drive torque also capped by the vendor 48 V T-N curve (docs/design/motor_candidates.json tn_curve, digitised from the RobStride manuals; evidence 186)'
m['assign'] = {jt: {'motor': a['module'], 'external_ratio': a['ratio'], 'link_efficiency': a['link_efficiency']} for jt, a in ax['axes'].items()}
m['assign'].update(ankle_pitch=None, ankle_roll=None)
m['assign_note'] = 'from sim/rl/rev3_b.json (one source); ankle_pitch is coupled to the knee in arch8 (no motor), ankle_roll is locked'
src = (f"FIT to the vendor overload table, RobStride/Product_Information@384cc56 RS04User Manual260713.pdf p.11 items 13-14 "
       f"(120..50 N·m -> 3..324 s, 40 N·m rated; 345x345 mm aluminium heat sink, 25 C, 50 rpm): {E}/eval/thermal_fit_rs04.py "
       f"(rotating table fit, log-time error; the stall table is NOT reproduced, the model is 2-4x slower there, as for RS03 in evidence 167)")
m['spec_override']['RS04'] = {k: {'value': v, 'unit': 'K/W' if k.startswith('r_') else 'J/K', 'estimate': False, 'fit': True, 'source': src}
                               for k, v in fit.items()}
# friction (joint side): module output coulomb 0.3 N·m (ESTIMATE as v2) and viscous from the manual no-load current;
# through an external stage coulomb x G and viscous x G^2 (four-bar: rms N over the knee band)
fb = ax['fourbar']
q = np.linspace(*fourbar_band(fb), 300)
_, N, _, _ = fourbar_N(q, fb['a'], fb['b'], fb['c'], np.radians(fb['beta_deg']), fb['branch'])
n_rms = float(np.sqrt(np.mean(N**2)))
no_load = {'RS03': (0.6, 2.36, 200), 'RS04': (2.0, 2.1, 200), 'RS06': (0.98, 1.09, 480)}   # A rms, kt N·m/A rms, rpm (manuals)
visc_out = {k: (i*kt - .3)/(rpm*np.pi/30) for k, (i, kt, rpm) in no_load.items()}
fr = out['friction']
for jt, a in ax['axes'].items():
    G = n_rms if a['ratio'] == 'fourbar' else float(a['ratio'])
    fr['coulomb'][jt] = round(.3*G, 3)
    fr['viscous'][jt] = round(visc_out[a['module']]*G*G, 4)
fr['rev3_note'] = (f"rev 3: coulomb 0.3 N·m x G, viscous b_out x G^2 per axis (b_out = (no-load current x kt - 0.3)/no-load speed: "
                   f"RS03 {visc_out['RS03']:.3f}, RS04 {visc_out['RS04']:.3f} (manual: 2 A rms at 200 rpm), RS06 {visc_out['RS06']:.3f}); "
                   f"knee four-bar rms N {n_rms:.2f} over its band")
json.dump(out, open('sim/rl/realism_robstride_rev3.json', 'w'), indent=1, ensure_ascii=False)
print('knee rms N', round(n_rms, 3), 'friction', fr['coulomb'], fr['viscous'])
